'use strict';

const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '../..');
const files = ['結構工具箱/assets/hy/colors_and_type.css', '結構工具箱/assets/home/home.css'];
const indexPath = path.join(repoRoot, '結構工具箱/index.html');
const startMarker = '<!-- home-critical:start -->';
const endMarker = '<!-- home-critical:end -->';

function extractMarked(source, label) {
  const chunks = [...source.matchAll(/\/\* critical:start \*\/([\s\S]*?)\/\* critical:end \*\//g)];
  const starts = (source.match(/\/\* critical:start \*\//g) || []).length;
  const ends = (source.match(/\/\* critical:end \*\//g) || []).length;
  if (!chunks.length || chunks.length !== starts || starts !== ends) throw new Error(`Invalid critical markers: ${label}`);
  return chunks.map(match => match[1]).join('\n').replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n').map(line => line.trim()).filter(Boolean).join('\n');
}

function buildCriticalCss() {
  const [tokens, home] = files.map(file => extractMarked(fs.readFileSync(path.join(repoRoot, file), 'utf8').replace(/\r\n?/g, '\n'), file));
  const css = `/* generated by build-home-critical-css.js; do not edit */\n:root {\n${tokens}\n}\n${home}\n`;
  if (Buffer.byteLength(css) > 6000) throw new Error(`Critical CSS exceeds 6000 bytes: ${Buffer.byteLength(css)}`);
  if (/<\/?(?:style|script)\b/i.test(css)) throw new Error('Critical CSS must not contain HTML element delimiters.');
  return css;
}

function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.some(arg => arg !== '--check')) throw new Error('Usage: node 結構工具箱/tools/build-home-critical-css.js [--check]');
  const css = buildCriticalCss();
  const source = fs.readFileSync(indexPath, 'utf8');
  const normalized = source.replace(/\r\n?/g, '\n');
  const pattern = /<!-- home-critical:start -->[\s\S]*?<!-- home-critical:end -->/;
  if (!pattern.test(normalized) || normalized.split(startMarker).length !== 2 || normalized.split(endMarker).length !== 2) throw new Error('Homepage must contain exactly one critical CSS output region.');
  const generated = normalized.replace(pattern, `${startMarker}\n<style>\n${css}</style>\n${endMarker}`);
  if (args.includes('--check')) {
    if (source !== generated) throw new Error('Homepage critical CSS is stale; run node 結構工具箱/tools/build-home-critical-css.js.');
  } else fs.writeFileSync(indexPath, generated, 'utf8');
  console.log(`homepage critical CSS ${args.includes('--check') ? 'in sync' : 'built'}: ${Buffer.byteLength(css)} bytes`);
}

if (require.main === module) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { buildCriticalCss, extractMarked };
